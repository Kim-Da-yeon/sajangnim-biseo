"""참가자 확인 시트 생성 스크립트.

흐름: 동결된 사례·조건을 읽어 사람이 원문과 대조하기 쉬운 표로 변환한다.
목적: AI 초안 라벨을 참가자가 직접 확인했다는 사실을 남기기 위한 양식이다.
결과 해석: 체크한 항목만 '참가자 확인'으로 보고서에 기재한다.
"""
import json, os

R = os.path.expanduser("~/sosang_agent")
cases = json.load(open(f"{R}/data/labels/eval_cases.json"))["cases"]
out = ["# 평가 라벨 확인 시트", "", "상태: AI 초안, 코덱스 2차 감사 반영. 참가자 확인 전. 프로필은 전부 가상.", "",
       "## 해석 확인 항목 (먼저 판단)", "",
       "| 확인 | 항목 | 현재 해석 |", "|---|---|---|",
       "| ☐ | \"이후\" 경계 | 기준일 당일 포함 (PA5, SM4) |",
       "| ☐ | 보은군 소재지 | 사업장만 보은군이면 표기 충돌로 확인 필요 (BE4) |",
       "| ☐ | 기관 판단 조항 | 공고 상태 합산에서 빼고 카드에 별도 표시 |",
       "| ☐ | 정책자금 범위 | 대리대출 일반경영안정·일시적 경영애로만 라벨 |",
       "| ☐ | 정책자금 기간 | 종료일 미표기라 일정 확인 필요 |", "",
       "## 사례 42개", "", "| 확인 | ID | 기준일 | 정답 | 기간 | 결정 조건 | 사유 |", "|---|---|---|---|---|---|---|"]
for x in cases:
    out.append(f"| ☐ | {x['id']} | {x['as_of']} | {x['expected']} | {x['period_status']} | {', '.join(x['decisive']) or '-'} | {x['reason']} |")
open(f"{R}/docs/label_review_sheet.md", "w").write("\n".join(out) + "\n")
print(len(cases))
