def body(find, blocks):
    out = [f"if(-not (Find {q(find)})){{ 'NOTFOUND {find}' }} else {{ SelPara; $h.Run('Delete')|Out-Null; Black"]
    first = True
    for b in blocks:
        if not first:
            out.append("Para; Black")
        first = False
        if isinstance(b, str):
            out.append(f"Ins {q(b)}")
        elif b[0] == "table":
            rows = "@(" + ",".join("(," + "@(" + ",".join(q(c) for c in r) + "))" if False else "@(" + ",".join(q(c) for c in r) + ")" for r in b[1]) + ")"
            out.append(f"Table {rows}")
        else:
            out.append(f"Pic {q(b[1])} {b[2]} {b[3]}")
